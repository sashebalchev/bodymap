// The text of src/figure-assets.ts: the figure drawing and its notice, inlined with esbuild's text loader.
// scripts/build.mjs writes it; test/figure.test.ts compares it with the checked-in file.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

export async function figureAssetsModule() {
  const bundle = await build({
    stdin: {
      contents: 'export { default as FIGURE_FRONT } from "./assets/figure/front.svg";\nexport { default as FIGURE_BACK } from "./assets/figure/back.svg";\nexport { default as FIGURE_NOTICE } from "./assets/figure/NOTICE.md";\n',
      resolveDir: root, sourcefile: "figure-assets",
    },
    bundle: true, write: false, format: "esm", charset: "ascii", loader: { ".svg": "text", ".md": "text" }, legalComments: "none",
  });
  return "// GENERATED by scripts/build.mjs from assets/figure/*. Do not edit; run npm run build.\n" + (bundle.outputFiles[0]?.text ?? "");
}
